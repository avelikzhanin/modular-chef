/// Пошаговые инструкции «как готовить» для выбранного способа.
/// Полностью локально — считается по ключевым словам метода из каталога,
/// без сети и токенов. Минуты подставляются из строки метода.
List<String> methodSteps(Module m, String method) {
  final low = method.toLowerCase();
  final t = _time(method);
  final name = m.name.toLowerCase();
  final isSide = m.category == ModuleCategory.side;
  final isSoup = m.category == ModuleCategory.soup;

  // У супов — свой точный рецепт с ингредиентами.
  final soupRecipe = _soupSteps[m.id];
  if (soupRecipe != null) return soupRecipe;

  if (low.contains('в фольге')) {
    return [
      'Разогрей духовку до 200°.',
      'Выложи $name на фольгу, сбрызни маслом, посоли, добавь лимон или травы.',
      'Заверни конверт блестящей стороной внутрь — сок останется внутри.',
      'Запекай $t — не открывай духовку раньше времени.',
      'Дай отдохнуть 5 минут прямо в фольге перед раскладкой.',
    ];
  }
  if (low.contains('запечь') && low.contains('пюрировать')) {
    return [
      'Разогрей духовку до 200°. Нарежь $name крупными кусками.',
      'Сбрызни маслом, посоли и запекай до мягкости (~${t.replaceAll('~', '')}).',
      'Переложи в блендер, добавь горячий бульон или сливки.',
      'Пробей до бархатной гладкости, доведи солью и специями.',
    ];
  }
  if (low.contains('запечь')) {
    return [
      'Разогрей духовку до 180–200°.',
      'Обсуши $name, натри маслом, солью и специями.',
      'Выложи на противень в один слой — так будет корочка, а не пар.',
      'Запекай $t, в середине можно перевернуть.',
      'Проверь готовность и дай отдохнуть 5 минут перед нарезкой.',
    ];
  }
  if (low.contains('гриль')) {
    return [
      'Раскали гриль или сковороду-гриль — на холодной будет тушиться.',
      'Обсуши $name бумажным полотенцем, смажь маслом, посоли.',
      'Жарь $t, переворачивая один раз — не двигай до полосок.',
      'Сними и дай отдохнуть пару минут, чтобы сок распределился.',
    ];
  }
  if (low.contains('сковород')) {
    return [
      'Разогрей сковороду со столовой ложкой масла на среднем огне.',
      'Выложи $name свободно, не в горку — иначе пустит сок.',
      'Готовь $t, помешивая или переворачивая.',
      'Соль и специи — в конце, чтобы не вытянуть влагу раньше времени.',
    ];
  }
  if (low.contains('тушить')) {
    return [
      'Быстро обжарь $name на сильном огне до лёгкой корочки.',
      low.contains('в соусе')
          ? 'Залей соусом так, чтобы почти покрывал.'
          : 'Добавь немного воды, бульона или соуса.',
      'Убавь огонь до слабого, накрой крышкой.',
      'Туши $t, изредка помешивая. В конце попробуй на соль.',
    ];
  }
  if (low.contains('отварить') || low.contains('варка')) {
    if (isSide) {
      return [
        'Промой $name холодной водой, пока она не станет прозрачной.',
        'Залей водой 1:2, посоли.',
        'Доведи до кипения, убавь огонь до слабого и накрой крышкой.',
        'Вари $t не перемешивая.',
        'Сними с огня и дай постоять 5 минут под крышкой, распуши вилкой.',
      ];
    }
    if (isSoup) {
      return [
        'Подготовь основу: обжарь овощи/лук в кастрюле пару минут.',
        'Добавь остальные ингредиенты и залей бульоном или водой.',
        'Доведи до кипения, сними пену, посоли.',
        'Вари на слабом огне $t под крышкой.',
        'Для крем-супа — пробей блендером до гладкости в конце.',
      ];
    }
    if (m.id == 'shrimp') {
      return [
        'Вскипяти подсоленную воду (можно с лимоном и лавровым листом).',
        'Опусти креветки в кипяток.',
        'Вари $t — до ярко-розового цвета, не дольше: станут резиновыми.',
        'Сразу откинь на дуршлаг или в ледяную воду, чтобы остановить нагрев.',
      ];
    }
    return [
      'Положи $name в холодную воду, чтобы покрывала целиком.',
      'Доведи до кипения и сними пену.',
      'Посоли, добавь лавровый лист и перец горошком.',
      'Вари на слабом огне $t под крышкой.',
      'Дай остыть прямо в бульоне — так сочнее. Бульон сохрани!',
    ];
  }
  if (low.contains('запарка')) {
    return [
      'Промой $name и переложи в глубокую миску или кастрюлю.',
      'Залей кипятком 1:1,5 и посоли.',
      'Накрой крышкой или тарелкой — огонь не нужен.',
      'Оставь $t, затем распуши вилкой.',
    ];
  }
  if (low.contains('на пару')) {
    return [
      'Вскипяти воду в кастрюле, сверху — пароварка или дуршлаг.',
      'Выложи $name в один слой, накрой крышкой.',
      'Готовь $t — до яркого цвета и лёгкой хрусткости.',
      'Сразу сними с пара, чтобы не переварить.',
    ];
  }
  if (low.contains('слабосол')) {
    return [
      'Смешай соль и сахар 2:1, можно добавить цедру или укроп.',
      'Обмажь $name смесью со всех сторон.',
      'Заверни в плёнку или положи в контейнер под лёгкий гнёт.',
      'Держи $t в холодильнике.',
      'Смой смесь, обсуши — готово к нарезке.',
    ];
  }
  if (low.contains('маринован')) {
    return [
      'Смешай маринад: масло + кислота (лимон/уксус) + соль и специи.',
      'Залей $name так, чтобы маринад касался всех сторон.',
      'Убери в холодильник на ${t.replaceAll('~', '')}, раз переверни.',
      'Перед готовкой дай стечь лишнему маринаду.',
    ];
  }
  if (low.contains('сырой')) {
    return [
      'Помой $name и хорошо обсуши.',
      'Храни целиком — нарезай прямо перед подачей, так дольше свежесть.',
    ];
  }
  if (low.contains('блендер')) {
    return [
      'Сложи все ингредиенты для «$name» в чашу блендера.',
      'Пробей до гладкости $t.',
      'Попробуй: доведи солью, кислотой или маслом.',
      'Переложи в чистую банку — храни по подсказке ниже.',
    ];
  }
  if (low.contains('уварить')) {
    return [
      'Выложи ингредиенты в сотейник на слабый огонь.',
      'Уваривай $t, часто помешивая, чтобы не пригорело.',
      'Готово, когда след от ложки на дне затягивается медленно.',
      'Остуди перед тем, как закрыть крышкой.',
    ];
  }
  if (low.contains('нарезка')) {
    return [
      'Помой и обсуши $name.',
      'Нарежь удобными кусочками $t.',
      'Сложи в контейнер, вниз — бумажное полотенце от влаги.',
    ];
  }
  if (low.contains('размять')) {
    return [
      'Разомни $name вилкой до нужной текстуры $t.',
      'Приправь солью, лимоном или маслом по вкусу.',
      'Подавай сразу — эта заготовка не любит ждать.',
    ];
  }
  if (low.contains('вафельниц')) {
    return [
      'Замеси тесто: мука, яйца, молоко, немного масла и сахара.',
      'Разогрей вафельницу, слегка смажь маслом.',
      'Выпекай $t до золотистого цвета.',
      'Остуди на решётке — на тарелке размякнут.',
      'Лишние — в морозилку: тостер вернёт им хруст за минуту.',
    ];
  }
  if (low.contains('без выпечки')) {
    return [
      'Смешай все ингредиенты в липкую массу.',
      'Скатай шарики или утрамбуй в форму $t.',
      'Охлади минимум 15 минут — станет держать форму.',
    ];
  }
  if (low.contains('слоями') || low.contains('залить молоком')) {
    return [
      'Возьми чистую банку с крышкой.',
      'Собери слои снизу вверх: основа → прослойка → фрукты → хруст.',
      'Залей молоком или йогуртом, если нужно, закрой крышкой.',
      'Ночь в холодильнике — утром завтрак готов.',
    ];
  }
  if (low.contains('утром')) {
    return [
      'Эта заготовка готовится свежей — утром, $t.',
      'С вечера можно подготовить сухую смесь или тесто.',
    ];
  }
  if (low.contains('сборка')) {
    return [
      'Подготовь все компоненты — помой, обсуши, нарежь.',
      'Собери «$name» $t.',
      'Заправку добавляй перед подачей, а не заранее.',
    ];
  }
  if (low.contains('готовое')) {
    return [
      '$name не требует готовки.',
      'Разложи порциями, чтобы удобно было брать.',
    ];
  }
  // Фолбэк — общая схема.
  return [
    'Подготовь $name: помой, обсуши, приправь.',
    'Готовь способом «$method».',
    'Остуди, разложи по контейнерам и подпиши дату.',
  ];
}

