/// «40мин» / «24ч» / «5–8 мин» из строки метода → читаемое «~40 минут».
String _time(String method) {
  final h = RegExp(r'(\d+)\s*ч').firstMatch(method);
  if (h != null) return '~${h.group(1)} ч';
  final range = RegExp(r'(\d+)\s*[–-]\s*(\d+)\s*мин').firstMatch(method);
  if (range != null) return '${range.group(1)}–${range.group(2)} минут';
  final min = RegExp(r'(\d+)\s*мин').firstMatch(method);
  if (min != null) return '~${min.group(1)} минут';
  return 'до готовности';
}
